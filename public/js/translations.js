function setLanguage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }
    });
    const btnFr = document.getElementById('btn-fr');
    const btnEn = document.getElementById('btn-en');
    if (btnFr && btnEn) {
        btnFr.classList.toggle('active', lang === 'fr');
        btnEn.classList.toggle('active', lang === 'en');
    }
    const btnFrMobile = document.getElementById('btn-fr-mobile');
    const btnEnMobile = document.getElementById('btn-en-mobile');
    if (btnFrMobile && btnEnMobile) {
        btnFrMobile.classList.toggle('active', lang === 'fr');
        btnEnMobile.classList.toggle('active', lang === 'en');
    }
    localStorage.setItem('preferredLang', lang);
}

// Appliquer la langue dès que le script est chargé (avant même le DOMContentLoaded)
const savedLang = localStorage.getItem('preferredLang') || 'fr';
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => setLanguage(savedLang));
} else {
    setLanguage(savedLang);
}